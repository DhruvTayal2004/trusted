import { createRequire } from 'node:module';
const { chromium } = createRequire(import.meta.url)('playwright');
const base = process.argv[2] ?? 'http://127.0.0.1:8081';
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 412, height: 915 } });
const logs = [];
page.on('console', (m) => logs.push(`[${m.type()}] ${m.text()}`));
page.on('pageerror', (e) => logs.push(`[pageerror] ${e.stack ?? e}`));
const txt = (t, o) => page.getByText(t, o).filter({ visible: true });
const tap = async (l) => { try { await l.click({ timeout: 4000 }); } catch { await l.evaluate((el) => (el.closest('[role=button],[tabindex],a,button') ?? el).click()); } };
await page.goto(base, { waitUntil: 'networkidle' });
await txt('New shop? Create owner account').click();
await page.getByPlaceholder('owner@example.com').fill(`probe-${Date.now().toString(36)}@test.local`);
await page.getByPlaceholder('••••••••').fill('Passw0rd!123');
await txt('Create account', { exact: true }).click();
await txt('Create your shop').first().waitFor({ timeout: 30_000 });
await page.getByPlaceholder('Sharma Kirana Store').fill('Probe Kirana');
await page.getByPlaceholder('Sharma ji').fill('Owner');
await txt('Create shop', { exact: true }).click();
await txt('Recorded sales').waitFor({ timeout: 60_000 }).catch(async (e) => { await page.screenshot({ path: 'e2e/out/probe-fail.png' }); console.log(logs.slice(-15).join('\n')); throw e; });
await tap(txt('More', { exact: true }).first());
await page.waitForTimeout(800);
logs.length = 0;
console.log('-- Settings then browser back');
await tap(txt('Settings').first());
await txt('Shop code for employee login').waitFor({ timeout: 20_000 });
await page.goBack();
await page.waitForTimeout(2500);
console.log(logs.filter((l) => /error|hook|above error/i.test(l)).map((l) => l.slice(0, 3000)).join('\n---\n') || '(no errors after back)');
await page.screenshot({ path: 'e2e/out/probe-after-back.png' });
logs.length = 0;
console.log('-- Sign out');
page.on('dialog', (d) => { console.log('dialog:', d.type(), d.message().slice(0, 80)); d.accept(); });
await tap(txt('Sign out of this device').first());
await page.waitForTimeout(800);
await txt('Sign out', { exact: true }).first().click({ timeout: 3000 }).catch(() => console.log('(no custom confirm button)'));
await page.waitForTimeout(4000);
await page.screenshot({ path: 'e2e/out/probe-signout.png' });
console.log(logs.map((l) => l.slice(0, 3000)).join('\n---\n'));
await browser.close();
